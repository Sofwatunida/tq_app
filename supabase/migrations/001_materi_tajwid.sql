-- Materi Tajwid berbasis data: surah -> ayat -> materi_tajwid -> highlight_tajwid
--
-- Cara menjalankan:
--   1. Buka Supabase Dashboard > SQL Editor > New query
--   2. Tempel seluruh isi file ini
--   3. Klik Run
--
-- File ini aman dijalankan berulang kali (idempotent).
